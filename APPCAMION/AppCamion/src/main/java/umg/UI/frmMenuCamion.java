    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        Camion camion = new Camion();
        camion.setModelo(txtCampoModelo.getText());
        camion.setTipo(txtCampoTipo.getText());
        camion.setPotencia(new BigDecimal(txtCampoPotencia.getText()));
        camion.setNoPlaca(txtCampoNoPlaca.getText());
        
        CamionDAO dao = new CamionDAO();
        try {
            dao.insertar(camion);
            JOptionPane.showMessageDialog(this, "datos guardados correctamente");
            cargarCamionDAO();
            limpiarCampos();
        } catch (SQLException error){
            JOptionPane.showMessageDialog(this, "Error: " + error);
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        idcamion = Integer.parseInt(txtCampoId.getText());
        
        if (idcamion == 0) {
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningun registro");
            return;
        }
        try {
            Camion camion = new Camion();
            camion.setIdCamion(idcamion);
            camion.setModelo(txtCampoModelo.getText());
            camion.setNoPlaca(txtCampoNoPlaca.getText());
            camion.setTipo(txtCampoTipo.getText());
            camion.setPotencia(new BigDecimal(txtCampoPotencia.getText()));
            
            CamionDAO dao = new CamionDAO();
            dao.actualizar(camion);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");

            limpiarCampos();
            cargarCamionDAO();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningun registro");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void tblDatosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDatosMouseClicked
        // TODO add your handling code here:
        int fila = tblDatos.getSelectedRow();
        if (fila >= 0){
            idcamion = Integer.parseInt(tblDatos.getValueAt(fila, 0).toString());
            txtCampoId.setText(tblDatos.getValueAt(fila, 0).toString());
            txtCampoModelo.setText(tblDatos.getValueAt(fila, 1).toString());
            txtCampoTipo.setText(tblDatos.getValueAt(fila, 2).toString());
            txtCampoPotencia.setText(tblDatos.getValueAt(fila, 3).toString());
            txtCampoNoPlaca.setText(tblDatos.getValueAt(fila, 4).toString());
        }
        
    }//GEN-LAST:event_tblDatosMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        idcamion = Integer.parseInt(txtCampoId.getText());
        if (idcamion == 0) {
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningun registro");
            return;
        }
        
        try {
            CamionDAO dao = new CamionDAO();
            dao.eliminar(idcamion);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            
            limpiarCampos();
            cargarCamionDAO();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e);
        }
        
        
        
    }//GEN-LAST:event_btnEliminarActionPerformed

