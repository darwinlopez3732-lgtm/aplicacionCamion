    private void cargarCamionDAO(){
        CamionDAO listar = new CamionDAO();
        
        try {
            List<Camion> lista = listar.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblDatos.getModel();
            modelo.setRowCount(0);
            for (Camion cam : lista){
                modelo.addRow(new Object[]
                    {cam.getIdCamion(), cam.getModelo(), cam.getTipo(),
                    cam.getPotencia(), cam.getNoPlaca()});
            }
                        
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "error al cargar los datos: " + e);
        }
    }
    
