    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        
        // Validar que el nombre no esté vacío
        if (txtNombre.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "El nombre de la ciudad es obligatorio");
            txtNombre.requestFocus();
            return;
        }
        
        // crear objeto de la clase ciudad
        Ciudad ciudad = new Ciudad();
        ciudad.setNombre(txtNombre.getText());
        
        // crear el objeto dao para almacenar los datos a partir de la clase CiudadDAO
        CiudadDAO dao = new CiudadDAO();
        try{
            dao.insertar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            cargarCiudadDAO();
            limpiarCampos();
        } catch (SQLException error){
            JOptionPane.showMessageDialog(this, "Error al guardar: " + error.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void limpiarCampos(){
        txtID.setText("");
        txtNombre.setText("");
        idCiudad = 0;
        txtNombre.requestFocus();
    }

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        idCiudad = Integer.parseInt(txtID.getText());
        if (idCiudad == 0){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
            return;
        }
        
        try{
            Ciudad ciudad = new Ciudad();
            ciudad.setIdCiudad(idCiudad);
            ciudad.setNombre(txtNombre.getText());
            
        // Capturar datos de las cajas de texto
            CiudadDAO ciudaddao = new CiudadDAO();
            ciudaddao.actualizar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos actualizados Correctamente");
            idCiudad = 0;
            
        // limpiar cajas de texto
            txtNombre.setText("");
            txtID.setText("");
            
        } catch (SQLException error){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
        }
        
    
        
        
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        idCiudad = Integer.parseInt(txtID.getText());
        if (idCiudad == 0){
            JOptionPane.showMessageDialog(this, "No se ha seleccionado ningún registro");
            return;
        }
        int confirmar = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este registro?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirmar == JOptionPane.YES_OPTION){
            try{
                CiudadDAO dao = new CiudadDAO();
                dao.eliminar(idCiudad);
                JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
                idCiudad = 0;
                txtNombre.setText("");
                txtID.setText("");
                cargarCiudadDAO();
            } catch (SQLException error){
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + error.getMessage());
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCiudadMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCiudadMouseClicked
        int fila = tblCiudad.getSelectedRow();
        if (fila >= 0){
            idCiudad = Integer.parseInt(tblCiudad.getValueAt(fila, 0).toString());
            txtID.setText(tblCiudad.getValueAt(fila, 0).toString());
            txtNombre.setText(tblCiudad.getValueAt(fila, 1).toString());
            
        }
    }//GEN-LAST:event_tblCiudadMouseClicked

