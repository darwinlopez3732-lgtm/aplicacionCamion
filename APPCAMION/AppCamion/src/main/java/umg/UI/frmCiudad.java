    private void cargarCiudadDAO(){
        CiudadDAO listarCiudades = new CiudadDAO();
        try{
            List<Ciudad> lista = listarCiudades.listar();
            DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
            
            modelo.setRowCount(0);
            
            //agregar datos a la tabla
            for (Ciudad c : lista){
                modelo.addRow(new Object[]{c.getIdCiudad(), c.getNombre()});
            }
            
        } catch (SQLException errorSQL){
            
        }
        
    }
